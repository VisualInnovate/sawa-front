const wording = (verb: string, skill: string, female: boolean): Wording => ({
  title: `${verb} {{name}} ${skill}`,
  half_strength: `بدأ{{f}} {{name}} ${verb} ${skill} بمساعدة جزئية`.replace("{{f}}", female ? "ت" : ""),
  half_weakness: `${female ? "لا تزال" : "لا يزال"} {{name}} ${female ? "تحتاج" : "يحتاج"} إلى مساعدة ${female ? "كي" : "كي"} ${verb} ${skill}`,
  half_plan_goal: `أن ${verb} {{name}} ${skill} باستقلالية في 4 من 5 محاولات`,
  zero_weakness: `${female ? "لا" : "لا"} ${verb} {{name}} ${skill}`,
  zero_plan_goal: `أن ${verb} {{name}} ${skill} بنجاح في 3 من 5 محاولات`,
  practice: `تدريب يومي قصير على أن ${verb} {{name}} ${skill}`,
});

export const SUB_GOALS: SubGoal[] = ITEMS.map(([domain, verbs, skill], i) => {
  const [m, f] = verbs.split("|");
  const order = (i % 5) + 1;
  return { id: 100 + i + 1, subtest_id: domain, question_type_id: domain, display_order: order, wording: { male: wording(m, skill, false), female: wording(f, skill, true) } };
});

export function wordingFor(goal: SubGoal, gender: string, name: string): Wording {
  const w = goal.wording[gender === "1" ? "female" : "male"];
  const out: any = {};
  for (const k of Object.keys(w) as (keyof Wording)[]) out[k] = w[k].replace(/\{\{name\}\}/g, name);
  return out;
}

/** الدرجات التي يضعها الديمو ليوسف: قوة في الأساسيات، ضعف يتدرّج مع ترتيب الهدف. */
export function demoScore(goal: SubGoal): 0 | 0.5 | 1 {
  const pattern: Record<number, Array<0 | 0.5 | 1>> = {
    1: [1, 1, 0.5, 0, 0], 2: [1, 0.5, 0, 0, 0], 3: [1, 1, 1, 0.5, 0], 4: [1, 1, 1, 1, 0.5],
    5: [1, 1, 0.5, 0, 0], 6: [1, 0.5, 0, 0, 0], 7: [1, 1, 0.5, 0.5, 0], 8: [1, 0.5, 0.5, 0, 0],
  };
  return pattern[goal.question_type_id][goal.display_order - 1];
}
